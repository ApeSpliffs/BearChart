#!/usr/bin/env python3
"""
Membership integrity: a plan sells only what a server enforces.

    python3 tools/test_membership.py

The membership config is generated by tools/build_data.py into data.json (and
from there into site-config.js). These tests read the shipped data.json and the
SQL in supabase/migrations/, so a plan can never promise an entitlement the
database does not grant, or sell one that only the page "enforces".
"""

import copy
import glob
import json
import os
import re
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

with open(os.path.join(ROOT, "data.json")) as f:
    DATA = json.load(f)
M = DATA["membership"]
FLAGS = DATA["config"].get("features") or {}


def has_entitlement_lists():
    """{tier: [features]} from the newest migration that defines has_entitlement."""
    newest = None
    for path in sorted(glob.glob(os.path.join(ROOT, "supabase", "migrations", "*.sql"))):
        with open(path) as f:
            sql = f.read()
        m = re.search(r"create or replace function (?:public\.)?has_entitlement\(.*?\$(\w*)\$(.*?)\$\1\$",
                      sql, re.S | re.I)
        if m:
            newest = (path, m.group(2))
    assert newest, "no migration defines has_entitlement"
    out = {}
    for tier, body in re.findall(r"when '(\w+)' then feature in \((.*?)\)", newest[1], re.S):
        out[tier] = re.findall(r"'(\w+)'", body)
    return os.path.basename(newest[0]), out


class PlansSellOnlyEnforcedFeatures(unittest.TestCase):

    def test_every_plan_entitlement_is_server_or_shop_enforced(self):
        for pid, plan in M["plans"].items():
            for e in plan["entitlements"]:
                d = M["entitlements"].get(e)
                self.assertIsNotNone(d, "%s sells an undefined entitlement %s" % (pid, e))
                self.assertIn(d["enforced"], ("server", "shop"),
                              "%s sells %s, which only the page enforces" % (pid, e))
                self.assertNotEqual(d.get("status"), "planned", "%s sells planned %s" % (pid, e))

    def test_every_feature_is_live_or_on_the_way(self):
        order = M["tiers_order"]
        for f in M["features"]:
            self.assertIn(f["status"], ("included", "soon"), f["id"])
            self.assertIn(f["from"], order, f["id"])
            if f["status"] != "included":
                continue
            if f["from"] in ("guest", "free"):
                self.assertNotIn("entitlement", f, "a free feature needs no entitlement: %s" % f["id"])
                continue
            e = f.get("entitlement")
            self.assertTrue(e, "paid feature %s works today but names no entitlement" % f["id"])
            self.assertIn(M["entitlements"][e]["enforced"], ("server", "shop"), f["id"])
            # Every tier from `from` up sells it.
            for tier in order[order.index(f["from"]):]:
                if tier in M["plans"]:
                    self.assertIn(e, M["plans"][tier]["entitlements"],
                                  "%s is included from %s but %s does not sell %s"
                                  % (f["id"], f["from"], tier, e))

    def test_on_the_way_is_derived_not_a_second_list(self):
        self.assertNotIn("on_the_way", M)
        soon = {f["entitlement"] for f in M["features"] if f["status"] == "soon"}
        self.assertIn("outfit_assembly", soon)

    def test_outfit_and_set_valuations_are_only_on_the_way(self):
        outfits = [f for f in M["features"] if f.get("entitlement") == "outfit_assembly"]
        self.assertEqual([f["status"] for f in outfits], ["soon"])
        for plan in M["plans"].values():
            self.assertNotIn("outfit_assembly", plan["entitlements"])
        self.assertEqual(M["entitlements"]["outfit_assembly"].get("status"), "planned")

    def test_showcase_is_a_server_entitlement_of_power(self):
        self.assertEqual(M["entitlements"]["showcase"]["enforced"], "server")
        self.assertIn("showcase", M["plans"]["power"]["entitlements"])
        self.assertNotIn("showcase", M["plans"]["pro"]["entitlements"])

    def test_plans_match_the_database(self):
        name, lists = has_entitlement_lists()
        for tier in ("pro", "power"):
            sold = {e for e in M["plans"][tier]["entitlements"]
                    if M["entitlements"][e]["enforced"] != "shop"}
            missing = sold - set(lists.get(tier, []))
            self.assertFalse(missing, "%s sells %s, which %s does not grant"
                             % (tier, sorted(missing), name))
        self.assertEqual(M["plans"]["free"]["entitlements"], [])

    def test_tiers_are_ordered_explicitly(self):
        self.assertEqual(M["tiers_order"], ["guest", "free", "pro", "power"])
        for pid in M["plans"]:
            self.assertIn(pid, M["tiers_order"])

    def test_no_coupon_amounts_in_the_shop_label(self):
        self.assertNotRegex(M["entitlements"]["shop_discount"]["label"], r"\$\d")


class CompsExportFlag(unittest.TestCase):

    def test_the_flag_ships_off(self):
        self.assertIs(FLAGS.get("comps_export"), False)

    def test_comps_export_is_absent_from_plans_while_off(self):
        self.assertFalse(FLAGS.get("comps_export"))
        for plan in M["plans"].values():
            self.assertNotIn("comps_export", plan["entitlements"])
        text = " ".join(f["text"] for f in M["features"])
        self.assertNotRegex(text, r"(?i)sold-price records|CSV")
        self.assertEqual(M["entitlements"]["comps_export"]["enforced"], "server")

    def test_the_flag_moves_the_card_and_the_gate_together(self):
        import build_data as B
        on = B.apply_feature_flags(copy.deepcopy(B.MEMBERSHIP), {"comps_export": True})
        self.assertIn("comps_export", on["plans"]["power"]["entitlements"])
        self.assertNotIn("comps_export", on["plans"]["pro"]["entitlements"])
        line = [f for f in on["features"] if f.get("entitlement") == "comps_export"]
        self.assertEqual(len(line), 1)
        self.assertEqual(line[0]["status"], "included")
        self.assertIn("stay free on every bear's page", line[0]["text"])
        # Applying twice changes nothing.
        again = B.apply_feature_flags(copy.deepcopy(on), {"comps_export": True})
        self.assertEqual(again, on)
        off = B.apply_feature_flags(copy.deepcopy(B.MEMBERSHIP), {"comps_export": False})
        self.assertNotIn("comps_export", off["plans"]["power"]["entitlements"])

    def test_the_database_grants_comps_export_to_power_only(self):
        _, lists = has_entitlement_lists()
        self.assertIn("comps_export", lists["power"])
        self.assertNotIn("comps_export", lists["pro"])


if __name__ == "__main__":
    unittest.main()
