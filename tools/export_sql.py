#!/usr/bin/env python3
"""
Emit seed.sql from data.json, so the researched observations can be loaded
straight into the Supabase schema.

    python3 tools/export_sql.py      ->  seed.sql

Apply the migrations in supabase/migrations/ first (supabase db push), then seed.sql. Re-running is safe: items are
upserted on their slug and sales are keyed on (item, price, date, listing).

    python3 tools/export_sql.py --merges-migration
        also (re)writes supabase/migrations/20261008000251_item_merges.sql from
        data.json's redirects and tools/catalogue_identity.json's sale overrides.
        Owner-run, and only before that migration has been applied anywhere:
        a migration that has run must never change.
"""

import argparse
import json
import os

ITEM_COLS = [
    "slug", "canonical_name", "aliases", "category", "species", "release_year",
    "release_month", "version", "variant", "licensed", "franchise", "limited_edition",
    "edition_size", "employee_exclusive", "store_exclusive", "event_exclusive",
    "vault_release", "original_release", "mini_bean", "retired", "is_lot",
    "international_exclusive", "online_exclusive",
    "sound", "scent", "rarity", "notes", "image_url", "image_credit", "image_source",
    "line", "variant_of", "variant_group", "size_in", "size_class", "catalogue_source",
]

SALE_COLS = [
    "sale_date", "sold_price", "price_high", "currency", "condition", "completeness",
    "marketplace", "source_url", "listing_id", "evidence_type", "shipping_included",
    "sample_size", "first_party", "notes",
    "ship_price", "seller_is_operator", "attributes", "excluded", "reassigned_from",
    "condition_basis", "variant_basis",
]
# jsonb columns: written as a json literal cast to jsonb.
JSONB_COLS = {"attributes", "excluded"}
# not null columns with a false default: a missing key is false, never null.
BOOL_COLS = {"first_party", "seller_is_operator"}
MERGES_MIGRATION = os.path.join("supabase", "migrations", "20261008000251_item_merges.sql")


def lit(v):
    if v is None or v == "":
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def sale_val(sale, c):
    v = sale.get(c)
    if c in JSONB_COLS:
        return "null" if v is None else lit(json.dumps(v, sort_keys=True)) + "::jsonb"
    if c in BOOL_COLS:
        return "true" if v else "false"
    return lit(v)


def arr(values):
    if not values:
        return "'{}'"
    return "array[" + ", ".join(lit(v) for v in values) + "]"


def merges_migration(data, ledger):
    """SQL that applies the identity ledger to a database seeded before it."""
    out = [
        "-- Item merges and sale overrides from tools/catalogue_identity.json.",
        "-- Generated by tools/export_sql.py --merges-migration; do not edit by hand.",
        "-- Each merge calls public.merge_item_slug (migration 20261008000250), which",
        "-- moves every reference - sales, collections, wishlists, showcases, photos,",
        "-- submissions, reports - to the surviving item. Idempotent.",
        "",
    ]
    for old, new in sorted((data.get("redirects") or {}).items()):
        out.append("select public.merge_item_slug(%s, %s);" % (lit(old), lit(new)))
    out.append("")
    sales = {s["id"]: s for s in data["sales"]}
    for sid, ov in sorted((ledger.get("sale_overrides") or {}).items()):
        s = sales.get(sid)
        if s is None:
            continue
        # Keyed the way seed.sql keys a sale; matched under either item, so it
        # works before and after the merge above.
        slugs = [s["item_id"]] + ([s["reassigned_from"]] if s.get("reassigned_from") else [])
        where = ("item_id in (select id from items where slug in (%s))\n"
                 "   and sold_price = %s and sale_date is not distinct from %s\n"
                 "   and listing_id is not distinct from %s"
                 % (", ".join(lit(x) for x in slugs), lit(s["sold_price"]),
                    lit(s.get("sale_date")), lit(s.get("listing_id"))))
        if ov.get("action") == "exclude":
            out.append("update sales set excluded = %s::jsonb\n where %s;"
                       % (lit(json.dumps(s.get("excluded"), sort_keys=True)), where))
        else:
            out.append("update sales set item_id = (select id from items where slug = %s),\n"
                       "       reassigned_from = %s\n where %s;"
                       % (lit(s["item_id"]), lit(s.get("reassigned_from")), where))
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--merges-migration", action="store_true",
                    help="also write %s" % MERGES_MIGRATION)
    args = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "data.json")) as f:
        data = json.load(f)

    if args.merges_migration:
        with open(os.path.join(root, "tools", "catalogue_identity.json")) as f:
            ledger = json.load(f)
        path = os.path.join(root, MERGES_MIGRATION)
        with open(path, "w") as f:
            f.write(merges_migration(data, ledger))
        print("wrote %s" % path)

    out = [
        "-- BearChart seed data, generated by tools/export_sql.py.",
        "-- Apply the migrations in supabase/migrations/ first.",
        "-- Source: the research transcribed in tools/build_data.py.",
        "",
        "begin;",
        "",
    ]

    for item in data["items"]:
        vals = []
        for c in ITEM_COLS:
            if c == "aliases":
                vals.append(arr(item.get("aliases")))
            elif c == "variant":
                # Deprecated column: carries the product line, now items.line.
                vals.append(lit(item.get("line")))
            elif c == "slug":
                # data.json keys items by "id"; the database calls it "slug".
                vals.append(lit(item["id"]))
            else:
                vals.append(lit(item.get(c)))
        out.append(
            "insert into items (%s)\nvalues (%s)\non conflict (slug) do update set\n  %s;"
            % (
                ", ".join(ITEM_COLS),
                ", ".join(vals),
                ",\n  ".join("%s = excluded.%s" % (c, c) for c in ITEM_COLS if c != "slug"),
            )
        )
        out.append("")

    for sale in data["sales"]:
        vals = ", ".join(sale_val(sale, c) for c in SALE_COLS)
        # Guarded so re-running the seed does not duplicate observations.
        out.append(
            "insert into sales (item_id, %s)\n"
            "select i.id, %s from items i where i.slug = %s\n"
            "  and not exists (\n"
            "    select 1 from sales s where s.item_id = i.id\n"
            "      and s.sold_price = %s\n"
            "      and s.sale_date is not distinct from %s\n"
            "      and s.listing_id is not distinct from %s\n"
            "      and s.notes is not distinct from %s);"
            % (
                ", ".join(SALE_COLS),
                vals,
                lit(sale["item_id"]),
                lit(sale["sold_price"]),
                lit(sale.get("sale_date")),
                lit(sale.get("listing_id")),
                lit(sale.get("notes")),
            )
        )
        out.append("")

    for key, value in data["config"].items():
        out.append(
            "insert into valuation_config (key, value) values (%s, %s::jsonb)\n"
            "on conflict (key) do update set value = excluded.value, updated_at = now();"
            % (lit(key), lit(json.dumps(value)))
        )
    out.append("")
    out.append("commit;")
    out.append("")

    path = os.path.join(root, "seed.sql")
    with open(path, "w") as f:
        f.write("\n".join(out))

    print("wrote %s" % path)
    print("  %d items, %d sales, %d config keys"
          % (len(data["items"]), len(data["sales"]), len(data["config"])))


if __name__ == "__main__":
    main()
