#!/usr/bin/env python3
"""Emit dist/config.js from the deploy environment.

    python3 tools/build_runtime_config.py > dist/config.js

The committed config.js is empty on purpose; this writes the per-environment
copy at build time (tools/build_site.sh). Standard library only. Every value
is JSON-encoded, so nothing in an environment variable can break out of the
string it lands in.

Environment (see docs/ENVIRONMENTS.md):
  BEARCHART_ENV                 development | preview | production
                                (falls back to Netlify's CONTEXT, then development)
  BEARCHART_SUPABASE_URL        } both set: accounts point at that project
  BEARCHART_SUPABASE_ANON_KEY   }
  BEARCHART_SENTRY_DSN          error reporting (observability.js); off if unset
  BEARCHART_POSTHOG_KEY         analytics project key; default is common.js's
  BEARCHART_POSTHOG_ON_PREVIEW  "1" to keep analytics on for previews
  COMMIT_REF                    release tag for error reports (set by Netlify)

A preview (a Netlify deploy preview or branch deploy, whatever BEARCHART_ENV
says) with no Supabase
settings gets accounts switched OFF: a preview must never talk to the
production database. Production with none falls back to
data.json's config (the behaviour before this file existed).
"""

import json
import os
import sys

ENVS = ("development", "preview", "production")


class ConfigError(ValueError):
    pass


# Netlify's CONTEXT for each kind of build, mapped onto ours.
NETLIFY_CONTEXTS = {
    "production": "production",
    "deploy-preview": "preview",
    "branch-deploy": "preview",
    "dev": "development",
}


def netlify_env(environ):
    return NETLIFY_CONTEXTS.get((environ.get("CONTEXT") or "").strip().lower())


def deploy_env(environ):
    value = (environ.get("BEARCHART_ENV") or "").strip().lower()
    if value in ENVS:
        return value
    return netlify_env(environ) or "development"


def is_preview(environ):
    """A Netlify deploy preview or branch deploy is a preview whatever
    BEARCHART_ENV says: a mis-scoped BEARCHART_ENV=production must not point a
    preview at the production database."""
    return netlify_env(environ) == "preview" or deploy_env(environ) == "preview"


def _local_url(url):
    return url.startswith(("http://localhost", "http://127.0.0.1"))


def build(environ):
    """The runtime object for this environment (a plain dict)."""
    env = deploy_env(environ)
    preview = is_preview(environ)
    runtime = {"env": env}

    url = (environ.get("BEARCHART_SUPABASE_URL") or "").strip()
    key = (environ.get("BEARCHART_SUPABASE_ANON_KEY") or "").strip()
    if url and key:
        if not (url.startswith("https://") or (env == "development" and _local_url(url))):
            raise ConfigError("BEARCHART_SUPABASE_URL must be an https:// address")
        runtime["auth"] = {"enabled": True, "supabase_url": url, "supabase_anon_key": key}
    elif url or key:
        raise ConfigError("set both BEARCHART_SUPABASE_URL and BEARCHART_SUPABASE_ANON_KEY, or neither")
    elif preview:
        runtime["auth"] = {"enabled": False}

    dsn = (environ.get("BEARCHART_SENTRY_DSN") or "").strip()
    if dsn:
        runtime["sentry_dsn"] = dsn
    posthog_key = (environ.get("BEARCHART_POSTHOG_KEY") or "").strip()
    if posthog_key:
        runtime["posthog_key"] = posthog_key
    if preview and environ.get("BEARCHART_POSTHOG_ON_PREVIEW") != "1":
        runtime["posthog_enabled"] = False
    release = (environ.get("COMMIT_REF") or "").strip()
    if release:
        runtime["release"] = release
    return runtime


def render(runtime):
    body = json.dumps(runtime, sort_keys=True, ensure_ascii=True)
    # Belt and braces: never emit a literal "<" (e.g. "</script>") even though
    # this is served as a .js file rather than inlined.
    body = body.replace("<", "\\u003c")
    return ("/* Generated by tools/build_runtime_config.py at deploy time. */\n"
            "window.BEARCHART_RUNTIME = %s;\n" % body)


def main():
    try:
        sys.stdout.write(render(build(os.environ)))
    except ConfigError as e:
        sys.stderr.write("build_runtime_config: %s\n" % e)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
