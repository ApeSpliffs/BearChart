#!/usr/bin/env python3
"""
Make BearChart installable, and make it work with no signal.

    python3 tools/build_pwa.py     (npm run pwa)

Writes manifest.webmanifest and sw.js. Icons are generated separately and
rarely change - see npm run icons.

WHY OFFLINE IS THE POINT, NOT A GARNISH
    The job this site exists for happens in a thrift store, holding a bear,
    with one bar of signal: is this worth the four dollars they want for it?
    A price guide that needs a connection is no use at the moment you need it.

    The whole catalogue is 82KB gzipped and the site is static files, so the
    entire thing fits in a cache. Installed, BearChart answers that question
    with the phone in aeroplane mode.

    It is also what any eventual app-store listing would rest on. Apple rejects
    repackaged websites; an offline price guide is a real application.
"""

import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The app shell: everything needed to open any page and price any bear with no
# network at all. The 2,042 generated item pages are NOT in here - they are
# cached as they are visited, and item/_offline.html covers the rest.
PRECACHE = [
    "./",
    "index.html", "item.html", "deals.html", "checklists.html",
    "collection.html", "admin.html", "about.html", "roadmap.html",
    "plans.html", "account.html",
    "item/_offline.html",
    "styles.css",
    "data.js", "engine.js", "icons.js", "auth.js", "entitlements.js",
    "submissions.js", "common.js", "app.js", "item.js", "deals.js", "checklists.js",
    "collection.js", "admin.js", "roadmap.js", "plans.js", "account.js",
    "manifest.webmanifest",
    "icons/icon-192.png", "icons/icon-512.png",
    "icons/icon-maskable-512.png", "icons/apple-touch-icon.png",
]


def version():
    """A cache name that changes exactly when the cached bytes change.

    Not a timestamp: rebuilding without changing anything would evict every
    visitor's cache for nothing, and on a phone that means re-downloading the
    catalogue to see the same thing.
    """
    h = hashlib.sha256()
    for rel in sorted(PRECACHE):
        path = os.path.join(ROOT, rel)
        if os.path.isfile(path):
            with open(path, "rb") as f:
                h.update(rel.encode())
                h.update(f.read())
    return h.hexdigest()[:12]


def write_manifest(data):
    meta = data["meta"]
    manifest = {
        "name": "BearChart — Build-A-Bear Price Guide",
        "short_name": "BearChart",
        "description": meta.get("subtitle") or "Build-A-Bear collector price guide",
        # Relative, so the app works served from a subdirectory as well as a
        # domain root - the same reason internal links are not root-relative.
        "start_url": "./index.html",
        "scope": "./",
        "display": "standalone",
        "orientation": "any",
        "background_color": "#fff6f2",
        "theme_color": "#b3131c",
        "categories": ["shopping", "utilities", "lifestyle"],
        "icons": [
            {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png",
             "purpose": "any"},
            {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png",
             "purpose": "any"},
            {"src": "icons/icon-maskable-512.png", "sizes": "512x512",
             "type": "image/png", "purpose": "maskable"},
        ],
        "shortcuts": [
            {"name": "My collection", "url": "./collection.html"},
            {"name": "Checklists", "url": "./checklists.html"},
            {"name": "Deals", "url": "./deals.html"},
        ],
    }
    path = os.path.join(ROOT, "manifest.webmanifest")
    with open(path, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    return path


SW_TEMPLATE = """/* BearChart service worker - generated by tools/build_pwa.py. Do not edit.
 *
 * The cache name carries a hash of everything precached, so it changes when
 * the content does and not when it does not.
 */
'use strict';

const CACHE = 'bearchart-%(version)s';
const PRECACHE = %(precache)s;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // addAll fails the whole install if any single file 404s. Cache them
    // individually so one missing asset cannot leave a visitor with no
    // offline support at all.
    await Promise.all(PRECACHE.map((url) =>
      cache.add(new Request(url, { cache: 'reload' })).catch(() => null)));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('bearchart-') && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

/** Serve from cache, and refresh it in the background for next time. */
async function staleWhileRevalidate(request) {
  const cache = await caches.open(CACHE);
  // ignoreVary: responses are stored compressed and carry
  // "Vary: accept-encoding". Without this, a cached entry fails to match a
  // request whose accept-encoding differs even slightly from the one the
  // worker used to precache it - which silently means no offline support at
  // all, with a full cache sitting right there.
  const hit = await cache.match(request, { ignoreVary: true });
  const fetching = fetch(request).then((res) => {
    if (res && res.ok && res.type === 'basic') cache.put(request, res.clone());
    return res;
  }).catch(() => null);
  return hit || (await fetching) || Response.error();
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;   // webfonts etc: leave alone

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const hit = await cache.match(request, { ignoreVary: true });
      if (hit) {
        event.waitUntil(fetch(request).then((res) => {
          if (res && res.ok) cache.put(request, res.clone());
        }).catch(() => null));
        return hit;
      }
      try {
        const res = await fetch(request);
        if (res && res.ok) cache.put(request, res.clone());
        return res;
      } catch (err) {
        // Offline, and this page was never visited. For an item page that is
        // the common case - nobody has opened the bear they are holding in a
        // shop. The stand-in shell renders it from the cached catalogue, and
        // the address bar still says which bear it is.
        if (/\\/item\\/[^/]+\\.html$/.test(url.pathname)) {
          const shell = await cache.match('item/_offline.html', { ignoreVary: true });
          if (shell) return shell;
        }
        const home = await cache.match('index.html', { ignoreVary: true });
        if (home) return home;
        throw err;
      }
    })());
    return;
  }

  event.respondWith(staleWhileRevalidate(request));
});
"""


def write_sw():
    path = os.path.join(ROOT, "sw.js")
    with open(path, "w") as f:
        f.write(SW_TEMPLATE % {
            "version": version(),
            "precache": json.dumps(PRECACHE, indent=2),
        })
    return path


def main():
    with open(os.path.join(ROOT, "data.json")) as f:
        data = json.load(f)

    # The manifest is itself precached, so it has to exist before the cache
    # version is hashed or every build would report it missing and the hash
    # would not cover it.
    print("wrote %s" % os.path.relpath(write_manifest(data), ROOT))

    missing = [p for p in PRECACHE
               if p != "./" and not os.path.isfile(os.path.join(ROOT, p))]
    print("wrote %s  (cache bearchart-%s, %d files precached)"
          % (os.path.relpath(write_sw(), ROOT), version(), len(PRECACHE) - len(missing)))
    if missing:
        print("\n  NOT on disk yet, so not precached:")
        for m in missing:
            print("    %s" % m)
        print("  run: npm run build && npm run pages && npm run icons")


if __name__ == "__main__":
    main()
