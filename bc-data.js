/*
 * BearChart data access. The ONLY module that knows where the data lives, what
 * format it is in, or that it arrives over fetch().
 *
 *   site-config.js (globalThis.BEARCHART_CONFIG)  config, membership, redirects,
 *                                                 stats, and the URLs below
 *   data/h/index.<hash>.json      every item + its valuation summary   loadIndex()
 *   data/h/listings.<hash>.json   active asking prices                 loadListings()
 *   data/h/plans.<hash>.json      the plans page's copy (features...)  loadPlans()
 *   data/items/<id>.json          one item, its sales and listings     loadItem(id)
 *
 * All generated by tools/build_assets.js from data.json. Pages use this through
 * common.js (BC.withCatalogue / BC.withItem); nothing else touches the files.
 *
 * Opened from file:// the browser blocks these requests, so the transport
 * refuses at once and the page says to use `npm start`.
 */
(function (root) {
  'use strict';

  // --- config (synchronous: site-config.js is a classic script) --------------

  function hasConfig() { return !!root.BEARCHART_CONFIG; }

  function config() {
    var c = root.BEARCHART_CONFIG;
    if (!c) throw new Error('BearChart: site-config.js did not load (run npm run build:dev).');
    return c;
  }

  /** A feature switch (tools/build_data.py FEATURE_FLAGS). Off unless exactly true. */
  function feature(name) {
    return hasConfig() && !!config().features && config().features[name] === true;
  }

  // Item ids merged into another item (tools/catalogue_identity.json) resolve
  // to the survivor everywhere, so an old link, bookmark, collection entry or
  // showcase never loses its bear. Chains are resolved at build time; the loop
  // guard only protects against a hand-edited file.
  function redirects() { return (hasConfig() && config().redirects) || {}; }

  function canonicalId(id) {
    var r = redirects();
    var seen = 0;
    while (id && Object.prototype.hasOwnProperty.call(r, id) && seen++ < 10) id = r[id];
    return id;
  }

  /**
   * Where "here" is, relative to the site root. Generated item pages live one
   * directory down (item/<slug>.html), and the site may be served from a
   * subdirectory, so links and data URLs get a prefix from the current path.
   */
  var PREFIX = /(^|\/)item\/[^/]*$/.test(root.location ? root.location.pathname : '') ? '../' : '';
  function rel(path) { return PREFIX + path; }

  // --- transport ------------------------------------------------------------

  function DataUnavailableError(message, info) {
    var e = new Error(message);
    e.name = 'DataUnavailableError';
    e.offline = !!(info && info.offline);
    e.file = !!(info && info.file);
    e.status = (info && info.status) || null;
    return e;
  }

  function defaultTransport(url) {
    if (root.location && root.location.protocol === 'file:') {
      return Promise.reject(DataUnavailableError(
        'Open BearChart through npm start; browsers block data files opened from disk.',
        { file: true }));
    }
    if (typeof root.fetch !== 'function') {
      return Promise.reject(DataUnavailableError('This browser cannot load data.', { offline: true }));
    }
    return root.fetch(url, { credentials: 'same-origin' }).then(function (res) {
      if (!res.ok) throw DataUnavailableError('Could not load ' + url + ' (' + res.status + ').',
                                              { status: res.status });
      return res.json();
    }, function () {
      throw DataUnavailableError('Could not reach BearChart to load ' + url + '.', { offline: true });
    });
  }

  var transport = defaultTransport;

  // --- load state (mirrored to <html data-bc-data="...">) -------------------

  var pending = 0;
  var current = 'idle';
  var listeners = [];

  function setState(s) {
    if (s === current) return;
    current = s;
    try {
      if (root.document && root.document.documentElement) {
        root.document.documentElement.setAttribute('data-bc-data', s);
      }
    } catch (e) { /* no DOM */ }
    listeners.forEach(function (fn) { try { fn(s); } catch (e) { /* a listener must not break loading */ } });
  }

  function fetchJson(path) {
    pending += 1;
    setState('loading');
    return Promise.resolve().then(function () { return transport(rel(path)); }).then(function (json) {
      pending -= 1;
      if (!pending) setState('ready');
      return json;
    }, function (err) {
      pending -= 1;
      setState('error');
      throw err;
    });
  }

  function engine() {
    var E = root.BearChartEngine;
    if (!E) throw new Error('BearChart: engine.js did not load.');
    return E;
  }

  // --- the catalogue (index) --------------------------------------------------

  function makeCatalogue(json) {
    var cfg = config().engine;
    var items = [];
    var byId = {};
    var summaries = {};
    var sold = {};
    (json.items || []).forEach(function (rec) {
      var item = {};
      Object.keys(rec).forEach(function (k) { if (k !== 'v' && k !== 'sc') item[k] = rec[k]; });
      items.push(item);
      byId[item.id] = item;
      summaries[item.id] = rec.v;
      sold[item.id] = rec.sc || [];
    });

    function itemById(id) { return byId[canonicalId(id)] || null; }

    // The index stores a lean summary (engine.js summary()); the bands are put
    // back once per item on first use. An id the index does not hold (an
    // admin draft) is valuated from no sales, which publishes nothing.
    var expanded = {};
    function valuationFor(id) {
      var c = canonicalId(id);
      if (!expanded[c]) {
        var E = engine();
        var s = summaries[c] || E.summary(E.valuate(byId[c] || { id: c }, [], cfg));
        expanded[c] = E.withBands(s, c, cfg);
      }
      return expanded[c];
    }

    return {
      items: items,
      meta: { schema: json.schema, generated_at: json.generated_at || null },
      recentSales: json.recent_sales || [],
      itemById: itemById,
      valuationFor: valuationFor,
      soldConditions: function (id) { return sold[canonicalId(id)] || []; }
    };
  }

  var indexPromise = null;
  function loadIndex() {
    if (!indexPromise) {
      indexPromise = fetchJson(config().data.index).then(makeCatalogue);
      indexPromise.catch(function () { indexPromise = null; });   // a retry may succeed
    }
    return indexPromise;
  }

  var listingsPromise = null;
  function loadListings() {
    if (!listingsPromise) {
      listingsPromise = fetchJson(config().data.listings).then(function (j) {
        return { fetched_at: j.fetched_at || null, listings: j.listings || [] };
      });
      listingsPromise.catch(function () { listingsPromise = null; });
    }
    return listingsPromise;
  }

  var plansPromise = null;
  /** The plans page's copy: {features, who_for, coupon_terms, hot_slot_note}. */
  function loadPlans() {
    if (!plansPromise) {
      var url = config().data && config().data.plans;
      plansPromise = url
        ? fetchJson(url).then(function (j) {
            return { features: j.features || [], who_for: j.who_for || {},
                     coupon_terms: j.coupon_terms || '', hot_slot_note: j.hot_slot_note || '' };
          })
        : Promise.reject(DataUnavailableError('This build has no plans file.', { status: 404 }));
      plansPromise.catch(function () { plansPromise = null; });
    }
    return plansPromise;
  }

  // --- one item (shard) ------------------------------------------------------

  var ITEM_CACHE_MAX = 50;
  var itemCache = new Map();

  function itemPath(id) {
    return (config().data.items_base || 'data/items/') + encodeURIComponent(id) + '.json';
  }

  function detailFrom(json) {
    var E = engine();
    return {
      item: json.item,
      sales: json.sales || [],
      listings: json.listings || [],
      listings_fetched_at: json.listings_fetched_at || null,
      related: json.related || [],
      retail_reference: json.retail_reference || null,
      valuation: E.valuate(json.item, json.sales || [], config().engine),
      partial: false
    };
  }

  /**
   * Offline and this bear was never opened: price it from the cached index
   * (summary level) rather than not at all. The comps need a connection.
   */
  function partialFrom(id, err) {
    return loadIndex().then(function (cat) {
      var item = cat.itemById(id);
      if (!item) throw err;
      // The summary, shaped like a full valuation with no per-sale detail.
      var v = Object.assign({ points: [], by_condition: {}, excluded_outliers: [],
                              operator_excluded: [], first_party_count: 0, ranged_count: 0,
                              why: ['You are offline, so this is the value from the catalogue ' +
                                    'saved on this device. The sales behind it load when you ' +
                                    'reconnect.'] },
                            cat.valuationFor(id));
      return { item: item, sales: null, listings: [], listings_fetched_at: null, related: [],
               valuation: v, partial: true };
    }, function () { throw err; });
  }

  function loadItem(id) {
    id = canonicalId(id);
    if (itemCache.has(id)) {
      var hit = itemCache.get(id);
      itemCache.delete(id);
      itemCache.set(id, hit);   // most recently used last
      return hit;
    }
    var p = fetchJson(itemPath(id)).then(detailFrom, function (err) {
      if (err && err.offline) return partialFrom(id, err);
      throw err;
    });
    itemCache.set(id, p);
    while (itemCache.size > ITEM_CACHE_MAX) itemCache.delete(itemCache.keys().next().value);
    p.then(function (d) { if (d.partial) itemCache.delete(id); },
           function () { itemCache.delete(id); });
    return p;
  }

  /**
   * Several items, a few requests at a time (the insurance export). A bear
   * whose file failed maps to {error} (error.offline / error.status say why).
   */
  function loadItems(ids, opts) {
    var queue = Array.from(new Set((ids || []).map(canonicalId)));
    var out = new Map();
    var n = Math.max(1, (opts && opts.concurrency) || 6);
    function worker() {
      var id = queue.shift();
      if (id === undefined) return Promise.resolve();
      return loadItem(id).then(function (d) { out.set(id, d); },
                               function (err) { out.set(id, { error: err }); })
        .then(worker);
    }
    var workers = [];
    for (var i = 0; i < n; i++) workers.push(worker());
    return Promise.all(workers).then(function () { return out; });
  }

  var api = {
    hasConfig: hasConfig,
    config: config,
    feature: feature,
    canonicalId: canonicalId,
    redirects: redirects,
    rel: rel,
    loadIndex: loadIndex,
    loadItem: loadItem,
    loadItems: loadItems,
    loadListings: loadListings,
    loadPlans: loadPlans,
    state: function () { return current; },
    onState: function (fn) { listeners.push(fn); },
    DataUnavailableError: DataUnavailableError,
    /** Test seam: fn(url) -> Promise<object>. Clears every memo. */
    _setTransport: function (fn) {
      transport = fn || defaultTransport;
      indexPromise = null; listingsPromise = null; plansPromise = null; itemCache.clear();
    }
  };

  root.BearChartData = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
